CREATE OR REPLACE FUNCTION private.layan_clean_offer_changes(
  p_old public.property_offers,p_changes jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SET search_path TO ''
AS \$function\$
DECLARE v jsonb := '{}'::jsonb; k text;
BEGIN
  IF jsonb_typeof(p_changes) IS DISTINCT FROM 'object' THEN RAISE EXCEPTION 'Invalid changes object'; END IF;
  FOR k IN SELECT jsonb_object_keys(p_changes) LOOP
    IF k = ANY (ARRAY[
      'title','city','area','property_type','listing_purpose','area_m2','bedrooms','bathrooms',
      'total_price','price_on_request','down_payment','paid_amount','remaining_amount',
      'remaining_installments','monthly_installment','assignment_fee','discount_amount',
      'discount_percent','description','image_urls','contact_name','contact_phone'
    ]::text[]) THEN
      v := v || jsonb_build_object(k,p_changes->k);
    END IF;
  END LOOP;
  RETURN v;
END
\$function\$;

CREATE OR REPLACE FUNCTION private.layan_apply_offer_changes(p_id bigint,p_changes jsonb)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS \$function\$
BEGIN
  UPDATE public.property_offers
  SET title=CASE WHEN p_changes ? 'title' THEN p_changes->>'title' ELSE title END,
      total_price=CASE WHEN p_changes ? 'total_price' THEN nullif(p_changes->>'total_price','')::numeric ELSE total_price END,
      description=CASE WHEN p_changes ? 'description' THEN p_changes->>'description' ELSE description END,
      area=CASE WHEN p_changes ? 'area' THEN p_changes->>'area' ELSE area END,
      area_m2=CASE WHEN p_changes ? 'area_m2' THEN nullif(p_changes->>'area_m2','')::numeric ELSE area_m2 END,
      updated_at=now()
  WHERE id=p_id;
END
\$function\$;
